"""Re-capture the product UI shots for the final consistency update, from the deployed application as it now stands (production e18ba36).
Read-only: GET page loads in headless Chromium; no access code is entered, nothing is launched, no model is called. Writes to a SEPARATE place
(public/captures/final/**, gitignored, and data/final.json), so the approved film's captures (product/, paired/) stay untouched as the fallback.

The same pages and the same framing boxes as before:
  * the historical diagnostic run's readiness report (Act 2: eval-ea13944e, the Original website evaluated on its own), task 2 and overview;
  * the canonical paired evaluation's report (Act 4 and Act 5: eval-1cf64d5e), overview and task 2;
  * the Workspace (Act 5), opened on the canonical run.
    python film/scripts/capture_final.py
"""
from __future__ import annotations

import asyncio
import hashlib
import json
import re
from pathlib import Path

FILM = Path(__file__).resolve().parents[1]
OUT = FILM / "public" / "captures" / "final"
BASE = "https://209-38-84-72.sslip.io"
HIST = "eval-ea13944e8ba5c08e8893426b2f8b1c8f"
CANON = "eval-1cf64d5eae90bcaeab531b4886140c14"
PAGES = {
    "report-hist-t2": (f"#/reports/{HIST}/tasks/2", {"quote": "h1.lc-title", "places": "p.lc-places", "side": "section.lc-side",
        "stats": "section.lc-side dl.lc-side-stats", "answer": "section.lc-side blockquote.lc-answer", "findings": "ul.lc-findings", "note": ".lc-evidence"},
        {"finding_class_day": ("li", "Listing cards omit 'class day'")}),
    "report-hist": (f"#/reports/{HIST}", {"note": ".lc-evidence"}, {"recommendations": ("section", "What slowed the agents down")}),
    "report-canon": (f"#/reports/{CANON}", {"title": "h1", "sides": ".lc-sides", "note": ".lc-evidence"}, {}),
    "report-canon-t2": (f"#/reports/{CANON}/tasks/2", {"title": "h1", "note": ".lc-evidence"}, {}),
    # opened on the canonical run (#/run/<id>), so nothing from a later evaluation can appear; framed on the headline and setup panel in the film
    "workspace": (f"#/run/{CANON}", {"title": "h1"}, {"setup": ("section", "New evaluation")}),
    "home": ("#/", {"title": "h1"}, {}),
}
REDACT = r"""() => { const out = []; const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (w.nextNode()) { const n = w.currentNode; for (const m of n.textContent.matchAll(/ar-a20-[\w-]+/g)) {
    const r = document.createRange(); r.setStart(n, m.index); r.setEnd(n, m.index + m[0].length); const b = r.getBoundingClientRect();
    out.push({ x: b.x, y: b.y + scrollY, width: b.width, height: b.height, reason: 'internal budget identifier' }); } } return out; }"""


async def main() -> None:
    from playwright.async_api import async_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}, device_scale_factor=2)
        page = await ctx.new_page()
        for name, (route, sels, texts) in PAGES.items():
            await page.goto(f"{BASE}/{route}")
            await page.wait_for_load_state("networkidle")
            await page.wait_for_timeout(3000)
            boxes = {}
            for key, sel in sels.items():
                el = await page.query_selector(sel)
                boxes[key] = await el.bounding_box() if el else None
            for key, (tag, text) in texts.items():
                el = page.locator(tag, has_text=text).last
                boxes[key] = await el.bounding_box() if await el.count() else None
            sy = await page.evaluate("window.scrollY")
            for v in boxes.values():
                if v:
                    v["y"] += sy
            png = await page.screenshot(full_page=True)
            (OUT / f"{name}.png").write_bytes(png)
            meta[name] = {"route": route, "viewport": [1440, 900], "device_scale_factor": 2, "image": f"captures/final/{name}.png",
                          "sha256": hashlib.sha256(png).hexdigest(), "height": await page.evaluate("document.documentElement.scrollHeight"),
                          "boxes": boxes, "redact": await page.evaluate(REDACT),
                          "text": re.sub(r"ar-a20-[\w-]+", "[internal id]", (await page.evaluate("document.querySelector('main')?.innerText || document.body.innerText"))[:6000])}
        await b.close()
    (FILM / "data" / "final.json").write_text(json.dumps({"note": "Generated by film/scripts/capture_final.py from the deployed product (read-only).",
                                                         "base": BASE, "production_commit": "e18ba36", "pages": meta}, indent=1, ensure_ascii=False) + "\n")
    for k, m in meta.items():
        print(k, m["height"], {b: (v and round(v["y"])) for b, v in m["boxes"].items()}, "redact", len(m["redact"]))


if __name__ == "__main__":
    asyncio.run(main())
