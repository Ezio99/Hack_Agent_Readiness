"""Capture genuine product UI for the film: the Before run's readiness report as the deployed product serves it. Read-only (GET page loads in
headless Chromium; no access code is entered, nothing is launched, no model is called). Writes public/captures/product/** (gitignored) and
data/product.json (committed: element boxes in CSS px for camera framing, SHA-256 of every file).

    python film/scripts/capture_product.py [--base https://209-38-84-72.sslip.io]
"""
from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
from pathlib import Path

FILM = Path(__file__).resolve().parents[1]
OUT = FILM / "public" / "captures" / "product"
BEFORE_EVAL = "eval-ea13944e8ba5c08e8893426b2f8b1c8f"
PAGES = {
    "report-before-t2": (f"#/reports/{BEFORE_EVAL}/tasks/2", {
        "quote": "h1.lc-title", "places": "p.lc-places", "side": "section.lc-side", "stats": "section.lc-side dl.lc-side-stats",
        "answer": "section.lc-side blockquote.lc-answer", "findings": "ul.lc-findings"}),
    "report-before": (f"#/reports/{BEFORE_EVAL}", {}),
}
# blocks located by their visible text (the finding cards the film frames)
TEXT_BOXES = {"report-before-t2": {"finding_class_day": "Listing cards omit 'class day'"},
              "report-before": {"recommendations": "What slowed the agents down"}}


async def main(base: str) -> None:
    from playwright.async_api import async_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    meta = {}
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}, device_scale_factor=2)
        page = await ctx.new_page()
        for name, (route, sels) in PAGES.items():
            await page.goto(f"{base}/{route}")
            await page.wait_for_load_state("networkidle")
            await page.wait_for_timeout(2500)
            boxes = {}
            for key, sel in sels.items():
                el = await page.query_selector(sel)
                boxes[key] = await el.bounding_box() if el else None
            for key, text in TEXT_BOXES.get(name, {}).items():
                el = page.locator("li" if key.startswith("finding") else "section", has_text=text).last
                boxes[key] = await el.bounding_box() if await el.count() else None
            sy = await page.evaluate("window.scrollY")
            for k, v in boxes.items():
                if v:
                    v["y"] += sy
            png = await page.screenshot(full_page=True)
            (OUT / f"{name}.png").write_bytes(png)
            meta[name] = {"route": route, "viewport": [1440, 900], "device_scale_factor": 2, "image": f"captures/product/{name}.png",
                          "sha256": hashlib.sha256(png).hexdigest(), "height": await page.evaluate("document.documentElement.scrollHeight"), "boxes": boxes}
        await b.close()
    (FILM / "data" / "product.json").write_text(json.dumps({"note": "Generated by film/scripts/capture_product.py from the deployed product (read-only).",
                                                           "base": base, "pages": meta}, indent=1) + "\n")
    print({k: {b: (v and round(v["y"])) for b, v in m["boxes"].items()} for k, m in meta.items()})


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="https://209-38-84-72.sslip.io")
    asyncio.run(main(ap.parse_args().base))
