"""Genuine screen recordings of the production application for the v3 film (Chrome DevTools screencast of a real Chromium page: every frame is what
the browser painted, with its real timestamp; nothing is drawn or simulated). Two modes:

  replay  (free, read-only)  the canonical evaluation's task-2 replay, side by side, stepped through with the product's own step controls.
      python film/scripts/capture_screen.py replay

  live    (PAID: exactly one paired evaluation, owner-authorized 2026-11-05; expected ~US$0.71, enforced per-run ceiling US$3.74)
      python film/scripts/capture_screen.py live            (token: OPERATOR_TOKEN in the gitignored film/.env)
      Pre-flight (all must hold, or it stops before touching the page): the worker is idle, nothing is running, production offers exactly one
      repetition of 6 agent runs, the enforced per-run reservation is <= US$3.74, the evaluation budget has room for it, and the token is present.
      The token is read from film/.env, typed into the page's password field BEFORE recording starts, and never printed, logged or saved.
      The Run button is clicked once. If the launch is refused, the script stops: no retry. Recording continues until the run finishes.

Frames: public/captures/screen/<mode>/NNNNN.jpg (gitignored) + data/screen-<mode>.json (timestamps, events; committed).
"""
from __future__ import annotations

import argparse
import asyncio
import base64
import json
import time
import urllib.request
from pathlib import Path

FILM = Path(__file__).resolve().parents[1]
BASE = "https://209-38-84-72.sslip.io"
CANON = "eval-1cf64d5eae90bcaeab531b4886140c14"
VIEW = {"width": 1880, "height": 1058}   # = a 1600x900 window at 85% browser zoom
DPR = 1800 / 1058                          # frames of about 3200x1800 device pixels
MAX_RESERVATION_USD = 3.74


def get(path: str) -> dict:
    with urllib.request.urlopen(BASE + path, timeout=30) as r:
        return json.loads(r.read())


class Recorder:
    def __init__(self, mode: str):
        self.dir = FILM / "public" / "captures" / "screen" / mode
        self.dir.mkdir(parents=True, exist_ok=True)
        for f in self.dir.glob("*.jpg"):
            f.unlink()
        self.frames: list[dict] = []
        self.events: list[dict] = []
        self.t0: float | None = None
        self.last = -1.0

    def event(self, what: str, **kw) -> None:
        t = (time.time() - self.t0) if self.t0 else 0.0
        self.events.append({"t": round(t, 3), "event": what, **kw})
        print(f"[{t:7.2f}s] {what} {kw if kw else ''}", flush=True)

    async def start(self, page, fps: float = 8) -> None:
        """Grab what the browser paints, as device-pixel JPEG screenshots, as fast as it allows (about 7-8 a second at 3200x1800), each with its
        real time. (The DevTools screencast is smoother but only CSS-pixel resolution, too soft for on-screen text in the film.)"""
        self.page, self.fps, self.running = page, fps, True
        self.t0 = time.time()

        async def loop():
            while self.running:
                t = time.time() - self.t0
                try:
                    buf = await self.page.screenshot(type="jpeg", quality=92)
                except Exception:
                    break
                name = f"{len(self.frames):05d}.jpg"
                (self.dir / name).write_bytes(buf)
                self.frames.append({"t": round(t, 3), "file": name})
                await asyncio.sleep(max(0.0, 1 / self.fps - (time.time() - self.t0 - t)))
        self.task = asyncio.ensure_future(loop())

    async def stop(self, meta: dict) -> None:
        self.running = False
        await self.task
        out = {"note": "Screen recording of the production application: device-pixel screenshots of a real Chromium page, each with its real time. Generated by film/scripts/capture_screen.py.",
               "base": BASE, "viewport": VIEW, "device_scale_factor": DPR, **meta, "events": self.events, "frames": self.frames}
        (FILM / "data" / f"screen-{meta['mode']}.json").write_text(json.dumps(out, indent=1) + "\n")
        print(f"{len(self.frames)} frames over {self.frames[-1]['t'] if self.frames else 0:.1f} s -> {self.dir}")


async def smooth_scroll(page, y: float, ms: int = 900) -> None:
    await page.evaluate("""([y, ms]) => new Promise(res => { const y0 = scrollY, t0 = performance.now();
      const step = now => { const k = Math.min(1, (now - t0) / ms), e = k < .5 ? 2 * k * k : 1 - (-2 * k + 2) ** 2 / 2; scrollTo(0, y0 + (y - y0) * e);
        k < 1 ? requestAnimationFrame(step) : res(); }; requestAnimationFrame(step); })""", [y, ms])


async def replay() -> None:
    from playwright.async_api import async_playwright
    url = f"{BASE}/#/reports/{CANON}/tasks/2"
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport=VIEW, device_scale_factor=DPR)
        page = await ctx.new_page()
        # warm the image cache: step through both replays once, then reload so recording starts from step 1
        await page.goto(url); await page.wait_for_load_state("networkidle"); await page.wait_for_timeout(1500)
        nexts = page.get_by_role("button", name="Next step")
        for i in range(await nexts.count()):
            for _ in range(14):
                if not await nexts.nth(i).is_enabled():
                    break
                await nexts.nth(i).click(); await page.wait_for_timeout(150)
        await page.wait_for_load_state("networkidle")
        await page.reload(); await page.wait_for_load_state("networkidle"); await page.wait_for_timeout(2000)
        head = await page.locator("h3, h2", has_text="Original website").first.bounding_box()
        target = (head["y"] + await page.evaluate("scrollY")) - 96 if head else 500   # the heading clears the sticky site header
        await page.evaluate("y => scrollTo(0, y)", target); await page.wait_for_timeout(600)   # framed before recording: nothing moves but the replay
        rec = Recorder("replay")
        await rec.start(page)
        rec.event("recording started", url=url, scrollY=target)
        await page.wait_for_timeout(1500)
        orig, ready = nexts.nth(0), nexts.nth(1)
        # which button belongs to which side: the Original website's player is the left one
        bx = [await nexts.nth(i).bounding_box() for i in range(2)]
        if bx[0]["x"] > bx[1]["x"]:
            orig, ready = ready, orig
        for s in range(2, 14):
            await orig.evaluate("e => e.click()"); rec.event("Original website: next step", step=s); await page.wait_for_timeout(560)
        await page.wait_for_timeout(900)
        for s in range(2, 4):
            await ready.evaluate("e => e.click()"); rec.event("Agent-ready website: next step", step=s); await page.wait_for_timeout(1900)
        await page.wait_for_timeout(2500)
        rec.event("recording ended")
        await rec.stop({"mode": "replay", "evaluation": CANON, "route": f"#/reports/{CANON}/tasks/2", "paid": False})
        await b.close()


def read_code(env_file: Path, var: str) -> str:
    """The access code / operator token from the gitignored .env (never printed)."""
    import re
    m = re.search(rf"^\s*(?:export\s+)?{re.escape(var)}\s*=\s*[\"']?([^\"'\s]+)", env_file.read_text(), re.M) if env_file.is_file() else None
    return m.group(1) if m else ""


async def live(env_file: Path, var: str, dry_run: bool = False) -> None:
    # ---- pre-flight: read-only checks; any failure stops before the page is touched ----
    code = read_code(env_file, var)
    if len(code) < 24:
        raise SystemExit(f"{var} missing or too short in {env_file}: nothing launched")
    cfg = get("/api/ironbark/config")
    opt = (cfg.get("evaluation") or {}).get("options") or [{}]
    budget = ((cfg.get("spending") or {}).get("budgets") or [{}])[0]
    checks = {
        "worker idle": (cfg.get("worker") or {}).get("state") == "idle" and not cfg.get("active"),
        "launch authorized and ready": (cfg.get("launch") or {}).get("ready") is True,
        "exactly one repetition offered": cfg.get("repetitions") == [1],
        "one run = 6 agent runs": opt[0].get("trials") == 6 and opt[0].get("repetitions") == 1,
        f"enforced reservation <= US${MAX_RESERVATION_USD}": (opt[0].get("reservation_usd") or 99) <= MAX_RESERVATION_USD,
        "budget has room": (budget.get("available_usd") or 0) >= (opt[0].get("reservation_usd") or 99),
    }
    print("pre-flight:", json.dumps({k: bool(v) for k, v in checks.items()}))
    print(f"budget before: A${budget.get('available_aud'):.2f} of A${budget.get('limit_aud'):.2f} available (US${budget.get('available_usd'):.2f}); "
          f"per-run reservation US${opt[0].get('reservation_usd')}")
    if not all(checks.values()):
        raise SystemExit("pre-flight failed: nothing launched")
    if dry_run:
        print("dry run: all pre-flight checks pass; nothing launched"); return
    before_ids = {j["id"] for j in (lambda d: d if isinstance(d, list) else d.get("jobs") or d.get("items") or [])(get("/api/ironbark/jobs"))}

    from playwright.async_api import async_playwright
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport=VIEW, device_scale_factor=DPR)
        page = await ctx.new_page()
        await page.goto(f"{BASE}/#/run"); await page.wait_for_load_state("networkidle"); await page.wait_for_timeout(2500)
        field = page.locator("#ws-operator-token")
        await field.fill(code)                                        # password field: the page shows dots only; the value is never printed
        run = page.locator("button.ws-run")
        await page.wait_for_timeout(500)
        if not await run.is_enabled():
            raise SystemExit("the Run button is not enabled (code not accepted locally, or the server is busy): nothing launched")
        label = (await run.inner_text()).strip()
        box = await page.locator("h1").first.bounding_box()
        await page.evaluate("scrollTo(0, 0)"); await page.wait_for_timeout(400)
        rec = Recorder("live")
        await rec.start(page)
        rec.event("recording started", route="#/run", button=label)
        await page.wait_for_timeout(1500)
        rb = await run.bounding_box()
        await page.evaluate("y => scrollTo(0, y)", max(0, rb["y"] + await page.evaluate("scrollY") - 640))
        await page.wait_for_timeout(2500)
        await run.evaluate("e => e.click()")                          # the one and only launch (the page's own button and handler)
        rec.event("clicked Run (one launch)")
        job = None
        for _ in range(40):
            await page.wait_for_timeout(500)
            h = await page.evaluate("location.hash")
            if h.startswith("#/run/eval-"):
                job = h.split("/")[-1]; break
            msg = await page.locator(".ws-alert, .ws-message, [role=alert]").all_inner_texts()
            if any("not accepted" in m or "could not" in m.lower() for m in msg):
                rec.event("launch refused", message=" | ".join(msg)[:200]); break
        if not job:
            await rec.stop({"mode": "live", "paid": True, "launched": False})
            await b.close()
            raise SystemExit("no evaluation started: stopping (no retry)")
        rec.event("evaluation started", job=job)
        # watch: the job pane, then a running agent's live panel
        await page.wait_for_timeout(2500)
        top = await page.locator(".ws-tabs").first.bounding_box()
        if top:
            await page.evaluate("y => scrollTo(0, y)", max(0, top["y"] + await page.evaluate("scrollY") - 260))
            rec.event("framed the running evaluation")
        watched = False
        deadline = time.time() + 15 * 60
        while time.time() < deadline:
            await page.wait_for_timeout(3000)
            if not watched:
                cells = page.locator("button.ws-cell-button")
                if await cells.count():
                    await cells.first.evaluate("e => e.click()"); watched = True
                    rec.event("opened a running agent's live view")
                    await page.wait_for_timeout(1500)
                    panel = await page.locator(".ws-agent-anchor").first.bounding_box()
                    if panel:
                        await page.evaluate("y => scrollTo(0, y)", max(0, panel["y"] + await page.evaluate("scrollY") - 90))
                        rec.event("framed the live agent panel")
            if time.time() - rec.t0 > 90:
                rec.fps = 2                                           # the long middle of the run: fewer frames, same real time
            state = get(f"/api/ironbark/jobs/{job}").get("state")
            if state not in ("queued", "preparing", "running", "starting"):
                rec.event("evaluation finished", state=state); break
        await page.wait_for_timeout(4000)
        await rec.stop({"mode": "live", "paid": True, "launched": True, "job": job, "button": label})
        await b.close()
    after = get(f"/api/ironbark/jobs/{job}")
    cfg2 = get("/api/ironbark/config")
    b2 = ((cfg2.get("spending") or {}).get("budgets") or [{}])[0]
    print(json.dumps({"job": job, "state": after.get("state"), "cost_usd": after.get("cost_usd") or after.get("actual_cost_usd"),
                      "budget_after_aud": b2.get("available_aud"), "new_job_was_new": job not in before_ids}))


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["replay", "live"])
    ap.add_argument("--env-file", type=Path, default=FILM / ".env")
    ap.add_argument("--var", default="OPERATOR_TOKEN")
    ap.add_argument("--dry-run", action="store_true", help="live: run the pre-flight checks only")
    a = ap.parse_args()
    asyncio.run(replay() if a.mode == "replay" else live(a.env_file, a.var, a.dry_run))
