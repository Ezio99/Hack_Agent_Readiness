"""Task 015 pilot / experiment driver: validates a product-generated recommendation with a controlled, budget-bounded experiment.

Order of events (each step is recorded; nothing is decided afterwards):
  1. an AUDIT report exists (finding + recommendation ids generated by the product);
  2. `plan` freezes a MANIFEST before any execution: audit/finding/recommendation references, frozen task + agent profile + website states + oracle, code hashes, schedule + seed,
     stopping rules, per-request/per-run/stage ceilings in USD and AUD, programme check; its SHA-256 is what the owner approves;
  3. `run` refuses unless the approved hash equals the manifest's hash and the code still hashes as recorded; every request passes the durable spend gate; one attempt per run, ever;
  4. the independent re-audit of the modified state and the analysis produce an EFFECT RECORD that references the original audit/finding/recommendation ids. The audit report is
     never modified; the effect is attached as a derived view only for LIVE results.
"Unmodified" / "modified" are labels of THIS experiment design only; the audit engine never sees them. A budget, provider or guard stop is a VOID run, never a website result."""
