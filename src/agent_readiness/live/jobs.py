"""Job manager for live evaluations: validation, one running job at a time, a hard wall-clock timeout, cancellation, and a status view DERIVED from the durable run directory (the single source of
truth: stage state, trial records, spend ledger), so a restarted API shows the same progress and any finished run can be reopened without running anything."""
from __future__ import annotations

import json
import os
import re
import secrets
import signal
import subprocess
import sys
import threading
import time
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlsplit

from ..investigate import export as exporter
from ..investigate.flow import STAGES
from ..investigate.run import InvestigationRun
from . import grant as G, worker
from .targets import TARGETS

JOB_TIMEOUT_SECONDS = 900
MAX_JOBS_PER_SESSION = 20
GOAL_MIN, GOAL_MAX = 5, 300
SECRET_ENV = re.compile(r"(KEY|TOKEN|SECRET|PASSWORD)", re.I)
MOCK_NOTICE = ("MOCK EVALUATION: pages were visited by a scripted browser agent, tasks were generated by rules from the captured site, and the investigator is a scripted test double whose claim was "
               "verified by the deterministic checker. No language model was called and nothing was spent. The goal is recorded but does not steer mock task generation.")


CONTEXT_LABEL = "CLIENT-SUPPLIED CONTEXT: a briefing written by the site owner. Unverified. It guided what to look at; it is not evidence about the website and no finding rests on it."
LIVE_NOTICE = ("LIVE EVALUATION: the language model was called for task generation, browsing and investigation. Cost is calculated from reported tokens at published prices (not a bill) and is hard-capped "
               "by the approved budget. Findings are labelled by how they were checked: verified by the deterministic checker, supported hypothesis, or unvalidated proposal.")
LIVE_TARGETS = ("ironbark",)                        # M1: live evaluations are restricted to the registered Ironbark demo site
DEV_NOTICE = ("DEV PROVIDER: this run used the loopback stand-in for the model endpoint (a fixture, not a model). The plumbing, spend gate and ledger are real; token counts and cost are calculated from "
              "fixture output, and nothing here says anything about model behaviour. Labels below that say LIVE describe the code path, not a model.")
ACTIVE = ("queued", "running")


@dataclass(frozen=True)
class LiveSettings:
    """Server-side live-evaluation policy. `key_env` names the variable the SERVER holds; the key value is read only when spawning an approved live worker."""
    enabled: bool = False
    cap_usd: float = 2.0
    global_budget_usd: float = 0.0
    base_url: str = "https://api.meta.ai/v1"
    model: str = "muse-spark-1.3"
    key_env: str = "META_MODEL_API_KEY"
    timeout_seconds: int = 1800
    allow_dev_provider: bool = False
    smoke_until: str = ""

    @property
    def smoke(self) -> bool:
        return self.smoke_until == "taskgen"

    @property
    def job_cap(self) -> float:
        """The maximum spend of ONE live job as the server will grant it: the task-generation allocation in smoke mode, else the configured cap."""
        return G.SMOKE_CAP_USD if self.smoke else self.cap_usd

    @classmethod
    def from_config(cls, c) -> "LiveSettings":
        return cls(enabled=c.live_enabled, cap_usd=c.live_job_cap_usd, global_budget_usd=c.live_budget_usd, base_url=c.live_model_base_url, key_env=c.live_api_key_env, timeout_seconds=c.live_job_timeout_seconds, allow_dev_provider=c.live_allow_dev_provider, smoke_until=c.live_smoke_until)

    def key(self) -> str | None:
        return os.environ.get(self.key_env) or None

    @property
    def dev_provider(self) -> bool:
        return urlsplit(self.base_url).hostname in ("127.0.0.1", "localhost", "::1")

    @property
    def endpoint_ok(self) -> bool:
        u = urlsplit(self.base_url)
        return bool(u.hostname) and not (u.username or u.password or u.query or u.fragment) and (u.scheme == "https" or (u.scheme == "http" and u.hostname in ("127.0.0.1", "localhost", "::1") and self.allow_dev_provider))

    def available(self) -> bool:
        return self.enabled and self.global_budget_usd > 0 and self.cap_usd > 0 and bool(self.key()) and self.endpoint_ok and self.smoke_until in ("", "taskgen")


def under_test_with_real_endpoint(endpoint: str) -> bool:
    """A test process (pytest) must never start a live job against a non-loopback endpoint: with a real key in the environment that would be a real, billed request. Subprocess workers inherit the marker."""
    return bool(os.environ.get("PYTEST_CURRENT_TEST")) and urlsplit(endpoint).hostname not in ("127.0.0.1", "localhost", "::1")


def clean_context(context: str | None) -> str | None:
    """The optional Website Context: printable text, whitespace-normalised per line, bounded. It is a client briefing, never evidence."""
    from .targets import CONTEXT_MAX
    if not context or not context.strip():
        return None
    text = "\n".join(" ".join(ln.split()) for ln in "".join(ch for ch in context if ch.isprintable() or ch == "\n").splitlines()).strip()
    if len(text) > CONTEXT_MAX:
        raise JobError(422, f"The website context must be at most {CONTEXT_MAX} characters.")
    return text or None


class JobError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status, self.message = status, message


class JobManager:
    def __init__(self, root: Path, *, timeout: int = JOB_TIMEOUT_SECONDS, killed=lambda: False, spawn=None, live: LiveSettings | None = None):
        self.root, self.timeout, self.killed, self.live = Path(root), timeout, killed, live or LiveSettings()
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._spawn = spawn or self._spawn_worker
        self.recover()

    # -- lifecycle -----------------------------------------------------------------------------------------------------------------
    def _spawn_worker(self, job_id: str) -> int:
        env = {k: v for k, v in os.environ.items() if not SECRET_ENV.search(k)}                 # no worker inherits a credential
        if worker.read(self.root, job_id)["mode"] == "live" and self.live.key():
            env[self.live.key_env] = self.live.key()                                            # ONLY an approved live job's worker receives the model key (environment, never argv, never a file)
            if self.live.dev_provider and self.live.allow_dev_provider:
                env["AR_ALLOW_LOOPBACK_MODEL"] = "1"                                            # the preflight accepts a loopback http endpoint only in this worker, only when the operator allowed the dev provider
        log = open(self.root / f"{job_id}.log", "ab")
        p = subprocess.Popen([sys.executable, "-m", "agent_readiness.live.worker", str(self.root), job_id], stdout=log, stderr=log, env=env, start_new_session=True)
        threading.Thread(target=lambda: (p.wait(), log.close()), daemon=True).start()          # reap the child: a finished worker must not linger as a zombie
        return p.pid

    @staticmethod
    def alive(pid: int | None, job_id: str | None = None) -> bool:
        """The worker process of this job is running (not a zombie, and not some other process that reused the pid)."""
        if not pid:
            return False
        try:
            os.kill(pid, 0)
            with open(f"/proc/{pid}/stat") as f:
                if f.read().rsplit(")", 1)[1].split()[0] == "Z":
                    return False
            if job_id:
                with open(f"/proc/{pid}/cmdline", "rb") as f:
                    cmd = f.read().decode(errors="replace")
                return "agent_readiness.live.worker" in cmd and job_id in cmd
            return True
        except (OSError, IndexError):
            return False

    def recover(self) -> None:
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running") and not self.alive(job.get("pid"), job["id"]):
                worker.update(self.root, job["id"], state="failed", error="The worker stopped unexpectedly (server restart or crash). The run directory is intact.", finished_at=time.time())

    def running(self) -> dict | None:
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running"):
                if self.alive(job.get("pid"), job["id"]) or job["state"] == "queued" and time.time() - job["created_at"] < 30:
                    return job
        return None

    def _live_reserved(self) -> float:
        """Budget already promised to live jobs: the full grant for one still running, what was actually committed (ledger) for a finished one."""
        total = 0.0
        for p in self.root.glob("*.job.json"):
            j = json.loads(p.read_text())
            if j["mode"] != "live" or not j.get("grant"):
                continue
            if j["state"] in ACTIVE:
                total += j["grant"]["budget_usd"]
            else:
                total += self._committed(j)
        return round(total, 6)

    def _committed(self, job: dict) -> float:
        rd = self.root / job["id"]
        try:
            return round(InvestigationRun(rd).ledger(job["grant"]["budget_usd"]).committed(), 6) if (rd / "run.json").exists() else 0.0
        except Exception:
            return float(job["grant"]["budget_usd"])                          # unknown: assume the worst

    def create(self, owner: str, target_id: str, goal: str, mode: str = "mock", confirm_budget_usd: float | None = None, context: str | None = None) -> dict:
        goal = " ".join(goal.split())
        context = clean_context(context)
        if target_id not in TARGETS:
            raise JobError(422, "Unknown target: only registered demo websites can be evaluated.")
        if not GOAL_MIN <= len(goal) <= GOAL_MAX:
            raise JobError(422, f"The evaluation goal must be {GOAL_MIN}-{GOAL_MAX} characters.")
        if mode not in ("mock", "live"):
            raise JobError(422, "Unknown evaluation mode.")
        if mode == "live":
            if target_id not in LIVE_TARGETS:
                raise JobError(422, "Live evaluation is limited to the registered Ironbark site in this build.")
            if not self.live.available():
                raise JobError(409, "Live model evaluation is not enabled on this server.")
            if under_test_with_real_endpoint(self.live.base_url):
                raise JobError(409, "Refusing: a test process may not start a live job against a real model endpoint.")
            if confirm_budget_usd is None or abs(float(confirm_budget_usd) - self.live.job_cap) > 1e-9:
                raise JobError(409, f"A live evaluation needs your explicit confirmation of its maximum spend (US${self.live.job_cap:.2f}).")
            if self._live_reserved() + self.live.job_cap > self.live.global_budget_usd + 1e-9:
                raise JobError(409, "The server's live-evaluation budget is exhausted.")
        if self.killed():
            raise JobError(503, "Evaluations are paused by the operator.")
        with self._lock:
            if self.running():
                raise JobError(409, "An evaluation is already running; wait for it to finish or cancel it.")
            if sum(1 for j in self.jobs(owner)) >= MAX_JOBS_PER_SESSION:
                raise JobError(429, "Evaluation limit for this session reached.")
            job_id = "live-" + secrets.token_hex(5)
            job = {"id": job_id, "owner": owner, "target_id": target_id, "goal": goal, "mode": mode, "state": "queued", "created_at": time.time(), "n_tasks": 4, "context": context,
                   "timeout_seconds": (600 if self.live.smoke else self.live.timeout_seconds) if mode == "live" else self.timeout}
            if mode == "live" and self.live.smoke:
                job["until"] = "taskgen"                          # operator smoke test: stop after task generation and freeze, before any browser trial, investigator or recommendation
            if mode == "live":                                    # the user's confirmation becomes ONE grant bound to this job, owner, target, goal, budget, model and stages
                job["grant"] = G.make_grant(job_id=job_id, owner=owner, target_id=target_id, goal=goal, budget_usd=self.live.job_cap, model=self.live.model, endpoint=self.live.base_url,
                                            snapshot_sha256=TARGETS[target_id].snapshot().sha256, stages=G.SMOKE_STAGES if self.live.smoke else G.LIVE_STAGES,
                                            limits=G.default_limits(smoke=self.live.smoke), context=context)
            worker.job_path(self.root, job_id).write_text(json.dumps(job, indent=2))
            self._spawn(job_id)                                  # the worker records its own pid and state
        timer = threading.Timer(job["timeout_seconds"], self._expire, args=(job_id,))
        timer.daemon = True                                  # never keeps the server (or a test) alive
        timer.start()
        return self.get(job_id, owner)

    def _expire(self, job_id: str) -> None:
        job = worker.read(self.root, job_id)
        if job["state"] in ("queued", "running"):
            self._kill(job)
            worker.update(self.root, job_id, state="timed_out", error=f"The evaluation exceeded its {job['timeout_seconds']}s limit and was stopped.", finished_at=time.time())

    def _kill(self, job: dict) -> None:
        if self.alive(job.get("pid"), job["id"]):
            try:
                os.killpg(job["pid"], signal.SIGTERM)
            except OSError:
                pass

    def cancel(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if job["state"] in ("queued", "running"):
            worker.update(self.root, job_id, state="cancelled", error="Cancelled by the user.", finished_at=time.time())
            self._kill(job)
        return self.get(job_id, owner)

    def cancel_all(self) -> int:
        n = 0
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running"):
                worker.update(self.root, job["id"], state="cancelled", error="Stopped by the operator.", finished_at=time.time())
                self._kill(job)
                n += 1
        return n

    # -- views ---------------------------------------------------------------------------------------------------------------------
    def _owned(self, job_id: str, owner: str) -> dict:
        p = worker.job_path(self.root, job_id) if re.fullmatch(r"live-[0-9a-f]{10}", job_id) else None
        if not p or not p.exists() or json.loads(p.read_text())["owner"] != owner:
            raise JobError(404, "No such evaluation.")           # other users' ids look the same as unknown ids
        return json.loads(p.read_text())

    def jobs(self, owner: str) -> list[dict]:
        out = [json.loads(p.read_text()) for p in self.root.glob("*.job.json")]
        return sorted((j for j in out if j["owner"] == owner), key=lambda j: -j["created_at"])

    def list(self, owner: str) -> list[dict]:
        return [{k: j.get(k) for k in ("id", "target_id", "goal", "mode", "state", "created_at", "finished_at")} for j in self.jobs(owner)]

    def get(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if job["state"] in ("queued", "running") and not self.alive(job.get("pid"), job["id"]) and time.time() - job["created_at"] > 30:
            job = worker.update(self.root, job_id, state="failed", error="The worker stopped unexpectedly.", finished_at=time.time())
        g = job.get("grant")
        return {**{k: job.get(k) for k in ("id", "target_id", "goal", "mode", "state", "error", "created_at", "started_at", "finished_at", "timeout_seconds")}, "mock": job["mode"] == "mock",
                "notice": MOCK_NOTICE if job["mode"] == "mock" else (DEV_NOTICE if self._dev(job) else LIVE_NOTICE), "dev_provider": self._dev(job), "stop": job.get("stop"), "until": job.get("until"),
                "smoke": self._smoke(job), "coverage": self._coverage(job),
                "grant": {"budget_usd": g["budget_usd"], "stages": g["stages"], "model": g["model"], "confirmed_at": g["confirmed_at"], "grant_sha256": g["grant_sha256"][:16]} if g else None,
                "client_context": ({"text": job["context"], "sha256": g["context_sha256"] if g else None, "label": CONTEXT_LABEL} if job.get("context") else None), **self._progress(job)}

    def _coverage(self, job: dict):
        """Goal coverage as verified by the independent check, from the run's task-generation report: complete, PARTIAL (with every unsupported or unverified aspect named) or insufficient."""
        p = self.root / job["id"] / "artifacts" / "taskgen-report.json"
        if not p.exists():
            return None
        gb = json.loads(p.read_text()).get("goal_binding")
        if not gb:
            return None
        cv = gb["coverage"]
        return {"status": cv["status"], "partial_because": cv["partial_because"], "unsupported_aspects": cv["unsupported_aspects"], "unverified_aspects": cv["unverified_aspects"], "missing_supported": cv["missing_supported"],
                "limitations": gb["analysis"]["limitations"], "limitation_details": gb["analysis"]["limitation_details"], "entities_covered": len(cv["entities_covered"]), "entities_total": cv["entities_total"],
                "relevant_tasks": gb["relevant_tasks"], "selected": gb["selected"]}

    def _smoke(self, job: dict):
        p = self.root / job["id"] / "artifacts" / "smoke-report.json"
        return json.loads(p.read_text()) if p.exists() else None

    @staticmethod
    def _dev(job: dict) -> bool:
        g = job.get("grant")
        return bool(g) and urlsplit(g["endpoint"]).hostname in ("127.0.0.1", "localhost", "::1")

    def _progress(self, job: dict) -> dict:
        rd = self.root / job["id"]
        if not (rd / "run.json").exists():
            return {"stages": [{"name": s, "status": "pending", "detail": None} for s in STAGES], "progress": 0.0, "trials": [], "events": [{"t": job["created_at"], "kind": "job", "text": "Evaluation queued."}],
                    "spend": self._spend(job, None), "opened": False}
        run = InvestigationRun(rd)
        st = run.state["stages"]
        stages = [{"name": s, "status": st[s]["status"], "detail": (st[s].get("summary") or {}).get("reason") if st[s].get("summary", {}).get("skipped") else None, "updated_at": st[s].get("updated_at")} for s in STAGES]
        done = sum(x["status"] == "done" for x in stages)
        trials, events = [], [{"t": job["created_at"], "kind": "job", "text": f"Evaluation of {job['target_id']} started."}]
        for s in stages:
            if s["status"] in ("done", "failed", "running"):
                events.append({"t": _ts(s["updated_at"]), "kind": "stage", "text": f"Stage {s['name']}: {s['status']}" + (f" ({s['detail']})" if s["detail"] else "")})
        tdir = rd / "artifacts" / "trials"
        planned = len(run.artifact("tasks-manifest")["tasks"]) if run.has_artifact("tasks-manifest") else None
        for f in sorted(tdir.glob("*.json")) if tdir.exists() else []:
            t = json.loads(f.read_text())
            m, ev = t.get("metrics", {}), t.get("evaluation", {})
            trials.append({"trial_id": t["trial_id"], "status": t["outcome"]["run_status"], "passed": ev.get("passed"), "evidence_backed": ev.get("evidence_backed"), "model_requests": m.get("model_requests"),
                           "page_views": m.get("page_views"), "cost_usd": m.get("calculated_cost_usd")})
            t0 = _ts(t.get("finished_at"))
            for j in t.get("journey", []):
                acts = ", ".join(str(x.get("name", "?")) + (f" {x['params']['url']}" if x.get("params", {}).get("url") else "") for x in j.get("actions", []))
                events.append({"t": t0, "kind": "trace", "text": f"{t['trial_id']} step {j['step']}: {j['path']} {acts}".strip()})
            events.append({"t": t0, "kind": "trial", "text": f"Trial {t['trial_id']}: {'passed' if ev.get('passed') else 'failed'}, {m.get('model_requests')} requests, {m.get('page_views')} page views"})
        if job.get("finished_at"):
            events.append({"t": job["finished_at"], "kind": "job", "text": f"Evaluation {job['state']}." + (f" {job['error']}" if job.get("error") else "")})
        prog = done / len(STAGES)
        if planned and st["baseline_trials"]["status"] != "done":
            prog += (len(trials) / planned) / len(STAGES) * (1 if st["baseline_trials"]["status"] == "running" else 0)
        for a in run.approvals():
            events.append({"t": _ts(a["at"]), "kind": "approval", "text": f"Approved stage {a['stage']} (manifest {a['manifest_sha256'][:12]}) within the user's grant"})
        if job.get("stop"):
            events.append({"t": job.get("finished_at"), "kind": "stop", "text": f"Stopped safely ({job['stop'].get('kind')}): {job['stop'].get('reason')}"})
        return {"stages": stages, "progress": round(min(prog, 1.0), 3) if job["state"] != "completed" else 1.0, "trials": trials, "tasks_planned": planned,
                "events": sorted(events, key=lambda e: e["t"] or 0)[-300:], "spend": self._spend(job, run), "opened": True}

    def _spend(self, job: dict, run) -> dict:
        """Recorded spend from the run's durable ledger, in total and per stage. Mock: always zero. Live: calculated at published prices (not a bill), against the grant's hard cap."""
        if job["mode"] == "mock":
            return {"committed_usd": 0.0, "hard_cap_usd": 0.0, "basis": "mock: no model call, nothing spent", "stages": {}}
        cap = job["grant"]["budget_usd"]
        if run is None:
            return {"committed_usd": 0.0, "hard_cap_usd": cap, "basis": "calculated at published prices; not a bill", "stages": {}}
        state: dict[str, float] = {}
        for e in run.ledger(cap).entries():
            if e["kind"] == "reserve":
                state.setdefault(e["id"], e["usd"])
            elif e["kind"] == "settle":
                state[e["id"]] = e["usd"]
        by = {"taskgen": 0.0, "baseline_trials": 0.0, "investigate": 0.0}
        for i, usd in state.items():
            by["taskgen" if "-taskgen" in i else "investigate" if "-investigate" in i else "baseline_trials"] += usd           # gate ids: <run>-taskgen:reqN, <run>-investigate:reqN, baseline-<task>-rN:reqN
        return {"committed_usd": round(sum(state.values()), 6), "hard_cap_usd": cap, "basis": "calculated at published prices; not a bill", "stages": {k: round(v, 6) for k, v in by.items()}}

    def export(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if not (self.root / job_id / "run.json").exists():
            raise JobError(409, "The evaluation has not produced a run yet.")
        data = exporter.export_run(self.root / job_id)
        exporter.check_clean(data)
        data["notices"] = [MOCK_NOTICE if job["mode"] == "mock" else (DEV_NOTICE if self._dev(job) else LIVE_NOTICE), *data.get("notices", [])]
        data["goal"] = job["goal"]
        data["client_context"] = {"text": job["context"], "sha256": job["grant"]["context_sha256"] if job.get("grant") else None, "label": CONTEXT_LABEL} if job.get("context") else None
        return data


def _ts(s) -> float | None:
    if s is None or isinstance(s, (int, float)):
        return s
    from datetime import datetime
    try:
        return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return None
