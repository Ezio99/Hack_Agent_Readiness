"""Job manager for live evaluations: validation, one running job at a time, a hard wall-clock timeout, cancellation, and a status view DERIVED from the durable run directory (the single source of
truth: stage state, trial records, spend ledger), so a restarted API shows the same progress and any finished run can be reopened without running anything."""
from __future__ import annotations

import json
import os
import re
import secrets
import signal
import subprocess
import sys
import threading
import time
from pathlib import Path

from ..investigate import export as exporter
from ..investigate.flow import STAGES
from ..investigate.run import InvestigationRun
from . import worker
from .targets import TARGETS

JOB_TIMEOUT_SECONDS = 900
MAX_JOBS_PER_SESSION = 20
GOAL_MIN, GOAL_MAX = 5, 300
SECRET_ENV = re.compile(r"(KEY|TOKEN|SECRET|PASSWORD)", re.I)
MOCK_NOTICE = ("MOCK EVALUATION: pages were visited by a scripted browser agent, tasks were generated by rules from the captured site, and the investigator is a scripted test double whose claim was "
               "verified by the deterministic checker. No language model was called and nothing was spent. The goal is recorded but does not steer mock task generation.")


class JobError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status, self.message = status, message


class JobManager:
    def __init__(self, root: Path, *, timeout: int = JOB_TIMEOUT_SECONDS, killed=lambda: False, spawn=None):
        self.root, self.timeout, self.killed = Path(root), timeout, killed
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = threading.Lock()
        self._spawn = spawn or self._spawn_worker
        self.recover()

    # -- lifecycle -----------------------------------------------------------------------------------------------------------------
    def _spawn_worker(self, job_id: str) -> int:
        env = {k: v for k, v in os.environ.items() if not SECRET_ENV.search(k)}                 # the worker never holds a credential in M0
        log = open(self.root / f"{job_id}.log", "ab")
        p = subprocess.Popen([sys.executable, "-m", "agent_readiness.live.worker", str(self.root), job_id], stdout=log, stderr=log, env=env, start_new_session=True)
        threading.Thread(target=lambda: (p.wait(), log.close()), daemon=True).start()          # reap the child: a finished worker must not linger as a zombie
        return p.pid

    @staticmethod
    def alive(pid: int | None, job_id: str | None = None) -> bool:
        """The worker process of this job is running (not a zombie, and not some other process that reused the pid)."""
        if not pid:
            return False
        try:
            os.kill(pid, 0)
            with open(f"/proc/{pid}/stat") as f:
                if f.read().rsplit(")", 1)[1].split()[0] == "Z":
                    return False
            if job_id:
                with open(f"/proc/{pid}/cmdline", "rb") as f:
                    cmd = f.read().decode(errors="replace")
                return "agent_readiness.live.worker" in cmd and job_id in cmd
            return True
        except (OSError, IndexError):
            return False

    def recover(self) -> None:
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running") and not self.alive(job.get("pid"), job["id"]):
                worker.update(self.root, job["id"], state="failed", error="The worker stopped unexpectedly (server restart or crash). The run directory is intact.", finished_at=time.time())

    def running(self) -> dict | None:
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running"):
                if self.alive(job.get("pid"), job["id"]) or job["state"] == "queued" and time.time() - job["created_at"] < 30:
                    return job
        return None

    def create(self, owner: str, target_id: str, goal: str, mode: str = "mock") -> dict:
        goal = " ".join(goal.split())
        if target_id not in TARGETS:
            raise JobError(422, "Unknown target: only registered demo websites can be evaluated.")
        if not GOAL_MIN <= len(goal) <= GOAL_MAX:
            raise JobError(422, f"The evaluation goal must be {GOAL_MIN}-{GOAL_MAX} characters.")
        if mode != "mock":
            raise JobError(409, "Live model evaluation is not enabled in this build; only mock evaluations can be started.")
        if self.killed():
            raise JobError(503, "Evaluations are paused by the operator.")
        with self._lock:
            if self.running():
                raise JobError(409, "An evaluation is already running; wait for it to finish or cancel it.")
            if sum(1 for j in self.jobs(owner)) >= MAX_JOBS_PER_SESSION:
                raise JobError(429, "Evaluation limit for this session reached.")
            job_id = "live-" + secrets.token_hex(5)
            job = {"id": job_id, "owner": owner, "target_id": target_id, "goal": goal, "mode": mode, "state": "queued", "created_at": time.time(), "n_tasks": 4, "timeout_seconds": self.timeout}
            worker.job_path(self.root, job_id).write_text(json.dumps(job, indent=2))
            self._spawn(job_id)                                  # the worker records its own pid and state
        timer = threading.Timer(self.timeout, self._expire, args=(job_id,))
        timer.daemon = True                                  # never keeps the server (or a test) alive
        timer.start()
        return self.get(job_id, owner)

    def _expire(self, job_id: str) -> None:
        job = worker.read(self.root, job_id)
        if job["state"] in ("queued", "running"):
            self._kill(job)
            worker.update(self.root, job_id, state="timed_out", error=f"The evaluation exceeded its {self.timeout}s limit and was stopped.", finished_at=time.time())

    def _kill(self, job: dict) -> None:
        if self.alive(job.get("pid"), job["id"]):
            try:
                os.killpg(job["pid"], signal.SIGTERM)
            except OSError:
                pass

    def cancel(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if job["state"] in ("queued", "running"):
            worker.update(self.root, job_id, state="cancelled", error="Cancelled by the user.", finished_at=time.time())
            self._kill(job)
        return self.get(job_id, owner)

    def cancel_all(self) -> int:
        n = 0
        for p in self.root.glob("*.job.json"):
            job = json.loads(p.read_text())
            if job["state"] in ("queued", "running"):
                worker.update(self.root, job["id"], state="cancelled", error="Stopped by the operator.", finished_at=time.time())
                self._kill(job)
                n += 1
        return n

    # -- views ---------------------------------------------------------------------------------------------------------------------
    def _owned(self, job_id: str, owner: str) -> dict:
        p = worker.job_path(self.root, job_id) if re.fullmatch(r"live-[0-9a-f]{10}", job_id) else None
        if not p or not p.exists() or json.loads(p.read_text())["owner"] != owner:
            raise JobError(404, "No such evaluation.")           # other users' ids look the same as unknown ids
        return json.loads(p.read_text())

    def jobs(self, owner: str) -> list[dict]:
        out = [json.loads(p.read_text()) for p in self.root.glob("*.job.json")]
        return sorted((j for j in out if j["owner"] == owner), key=lambda j: -j["created_at"])

    def list(self, owner: str) -> list[dict]:
        return [{k: j.get(k) for k in ("id", "target_id", "goal", "mode", "state", "created_at", "finished_at")} for j in self.jobs(owner)]

    def get(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if job["state"] in ("queued", "running") and not self.alive(job.get("pid"), job["id"]) and time.time() - job["created_at"] > 30:
            job = worker.update(self.root, job_id, state="failed", error="The worker stopped unexpectedly.", finished_at=time.time())
        return {**{k: job.get(k) for k in ("id", "target_id", "goal", "mode", "state", "error", "created_at", "started_at", "finished_at", "timeout_seconds")}, "mock": job["mode"] == "mock",
                "notice": MOCK_NOTICE if job["mode"] == "mock" else None, **self._progress(job)}

    def _progress(self, job: dict) -> dict:
        rd = self.root / job["id"]
        if not (rd / "run.json").exists():
            return {"stages": [{"name": s, "status": "pending", "detail": None} for s in STAGES], "progress": 0.0, "trials": [], "events": [{"t": job["created_at"], "kind": "job", "text": "Evaluation queued."}],
                    "spend": {"committed_usd": 0.0, "hard_cap_usd": 0.0, "basis": "mock: no model call, nothing spent"}, "opened": False}
        run = InvestigationRun(rd)
        st = run.state["stages"]
        stages = [{"name": s, "status": st[s]["status"], "detail": (st[s].get("summary") or {}).get("reason") if st[s].get("summary", {}).get("skipped") else None, "updated_at": st[s].get("updated_at")} for s in STAGES]
        done = sum(x["status"] == "done" for x in stages)
        trials, events = [], [{"t": job["created_at"], "kind": "job", "text": f"Evaluation of {job['target_id']} started."}]
        for s in stages:
            if s["status"] in ("done", "failed", "running"):
                events.append({"t": _ts(s["updated_at"]), "kind": "stage", "text": f"Stage {s['name']}: {s['status']}" + (f" ({s['detail']})" if s["detail"] else "")})
        tdir = rd / "artifacts" / "trials"
        planned = len(run.artifact("tasks-manifest")["tasks"]) if run.has_artifact("tasks-manifest") else None
        for f in sorted(tdir.glob("*.json")) if tdir.exists() else []:
            t = json.loads(f.read_text())
            m, ev = t.get("metrics", {}), t.get("evaluation", {})
            trials.append({"trial_id": t["trial_id"], "status": t["outcome"]["run_status"], "passed": ev.get("passed"), "evidence_backed": ev.get("evidence_backed"), "model_requests": m.get("model_requests"),
                           "page_views": m.get("page_views"), "cost_usd": m.get("calculated_cost_usd")})
            t0 = _ts(t.get("finished_at"))
            for j in t.get("journey", []):
                acts = ", ".join(str(x.get("name", "?")) + (f" {x['params']['url']}" if x.get("params", {}).get("url") else "") for x in j.get("actions", []))
                events.append({"t": t0, "kind": "trace", "text": f"{t['trial_id']} step {j['step']}: {j['path']} {acts}".strip()})
            events.append({"t": t0, "kind": "trial", "text": f"Trial {t['trial_id']}: {'passed' if ev.get('passed') else 'failed'}, {m.get('model_requests')} requests, {m.get('page_views')} page views"})
        if job.get("finished_at"):
            events.append({"t": job["finished_at"], "kind": "job", "text": f"Evaluation {job['state']}." + (f" {job['error']}" if job.get("error") else "")})
        prog = done / len(STAGES)
        if planned and st["baseline_trials"]["status"] != "done":
            prog += (len(trials) / planned) / len(STAGES) * (1 if st["baseline_trials"]["status"] == "running" else 0)
        try:
            committed = round(run.ledger(20.0).committed(), 6)
        except Exception:
            committed = 0.0
        return {"stages": stages, "progress": round(min(prog, 1.0), 3) if job["state"] != "completed" else 1.0, "trials": trials, "tasks_planned": planned,
                "events": sorted(events, key=lambda e: e["t"] or 0)[-300:], "spend": {"committed_usd": committed, "hard_cap_usd": 0.0 if job["mode"] == "mock" else None, "basis": "mock: no model call, nothing spent" if job["mode"] == "mock" else "calculated"},
                "opened": True}

    def export(self, job_id: str, owner: str) -> dict:
        job = self._owned(job_id, owner)
        if not (self.root / job_id / "run.json").exists():
            raise JobError(409, "The evaluation has not produced a run yet.")
        data = exporter.export_run(self.root / job_id)
        exporter.check_clean(data)
        if job["mode"] == "mock":
            data["notices"] = [MOCK_NOTICE, *data.get("notices", [])]
        data["goal"] = job["goal"]
        return data


def _ts(s) -> float | None:
    if s is None or isinstance(s, (int, float)):
        return s
    from datetime import datetime
    try:
        return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()
    except ValueError:
        return None
