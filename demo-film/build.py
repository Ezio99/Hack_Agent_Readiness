"""Project reviewed evidence and manifest into self-contained static preview inputs."""
import argparse
import html
import json
import re
from pathlib import Path
from evidence_adapter import load, captures

ROOT = Path(__file__).resolve().parent
COMPONENTS = {'hook', 'product', 'behavior', 'improvement', 'results', 'vision'}


def resolve(text, context):
    def replace(match):
        value = context
        for key in match[1].split('.'):
            value = value.get(key) if isinstance(value, dict) else None
        return 'unavailable' if value is None else str(value)
    return re.sub(r'\{([a-z_.]+)\}', replace, text)


def build(manifest_path=ROOT / 'demo-manifest.json'):
    manifest = json.loads(manifest_path.read_text())
    if manifest['schema'] != 'demo-manifest-v1':
        raise ValueError('Unsupported demo manifest')
    scenes = [s for s in manifest['scenes'] if s.get('visible', True)]
    ids = [s['id'] for s in scenes]
    if len(ids) != len(set(ids)) or not scenes:
        raise ValueError('Visible scenes must have unique IDs')
    for scene in scenes:
        if not re.fullmatch(r'\d{2}-[a-z]+', scene['id']) or scene['component'] not in COMPONENTS:
            raise ValueError('Invalid scene ID/component')
        if scene['emphasis'] not in {'concept', 'workflow', 'focus-event', 'sequence', 'illustration', 'metrics'}:
            raise ValueError('Unknown visual emphasis')
    evidence = load(ROOT, manifest)
    payload = {'presentation': manifest['presentation'], 'scenes': scenes,
               'evidence': evidence, 'captures': captures(ROOT, manifest, evidence)}
    (ROOT / 'generated').mkdir(exist_ok=True)
    (ROOT / 'frames').mkdir(exist_ok=True)
    (ROOT / 'exports').mkdir(exist_ok=True)
    serialized = json.dumps(payload, ensure_ascii=False, indent=2).replace('<', '\\u003c').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
    (ROOT / 'generated/film-data.js').write_text('/* Generated by build.py. Edit demo-manifest.json, not this file. */\nwindow.FILM = ' + serialized + ';\n')
    narration = '\n\n'.join(f"{s['time']} | {s['id']}\n{resolve(s['voiceover'], {'evidence': evidence})}" for s in scenes)
    (ROOT / 'generated/narration.txt').write_text(narration + '\n')
    for path in (ROOT / 'frames').glob('*.html'):
        if path.stem not in ids:
            path.unlink()
    for path in (ROOT / 'exports').glob('*.png'):
        if path.stem not in ids + ['contact-sheet']:
            path.unlink()
    for scene in scenes:
        title = html.escape(' '.join(scene['headline']))
        (ROOT / f"frames/{scene['id']}.html").write_text(f'''<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=1920">
<title>Agent Readiness · {title}</title><link rel="stylesheet" href="../film.css">
<body class="frame" data-scene="{scene['id']}"><main aria-label="Static storyboard frame"></main>
<script src="../generated/film-data.js"></script><script src="../scenes.js"></script></body></html>\n''')
    cards = []
    for scene in scenes:
        title = html.escape(' '.join(scene['headline']))
        caption = html.escape(scene['provenance'])
        cards.append(f'''<figure><a href="frames/{scene['id']}.html"><img src="exports/{scene['id']}.png" alt="{title} {caption}"></a><figcaption><span>{title}</span><span>{html.escape(scene['time'])}</span></figcaption><p class="tag">{caption}</p></figure>''')
    (ROOT / 'index.html').write_text('''<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Agent Readiness · Checkpoint A.1</title><link rel="stylesheet" href="tokens.css"><style>
*{box-sizing:border-box}body{margin:0;padding:52px 60px;background:var(--canvas);color:var(--text);font-family:var(--font)}header{display:flex;justify-content:space-between;align-items:end;margin-bottom:38px}h1{font-size:42px;letter-spacing:-.04em;margin:0}p{color:var(--secondary);font-size:19px;margin:12px 0 0}.grid{display:grid;grid-template-columns:1fr 1fr;gap:28px}figure{margin:0}img{width:100%;display:block;border:1px solid #294058;border-radius:10px}figcaption{font-size:18px;color:var(--secondary);margin:12px 0 4px;display:flex;justify-content:space-between}a{color:var(--accent);text-decoration:none}a:focus-visible{outline:3px solid var(--accent);outline-offset:6px}.tag{font-size:16px;color:var(--accent)}@media(max-width:800px){body{padding:25px}.grid{grid-template-columns:1fr}header{display:block}h1{font-size:28px}}
</style><header><div><span class="tag">CHECKPOINT A.1 · STATIC DESIGN REVIEW</span><h1>Agent Readiness</h1><p>One developer story. Evidence and illustration clearly labelled.</p></div><p>1920 × 1080 each · No animation</p></header><main class="grid">''' + '\n'.join(cards) + '</main></html>\n')
    return payload


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--manifest', type=Path, default=ROOT / 'demo-manifest.json')
    build(parser.parse_args().manifest)
    print('Built static presentation inputs from explicitly selected, hash-checked public evidence.')
